import os
import re
import uuid
import time
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, Optional, List
from xml.sax.saxutils import escape as xml_escape

from reportlab.lib.pagesizes import letter
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
    KeepTogether,
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

# Storage directory for generated PDFs
STORAGE_DIR = Path(__file__).resolve().parent.parent.parent / "storage" / "generated_pdfs"
STORAGE_DIR.mkdir(parents=True, exist_ok=True)

# In-memory registry of generated PDFs
GENERATED_PDF_REGISTRY: Dict[str, Dict[str, Any]] = {}


def sanitize_filename(name: str) -> str:
    """Sanitize filename to prevent directory traversal and remove invalid characters."""
    clean = re.sub(r'[\\/*?:"<>|]', "", name).strip()
    clean = re.sub(r"\s+", "_", clean)
    if not clean:
        clean = "document"
    if not clean.lower().endswith(".pdf"):
        clean += ".pdf"
    return clean


def format_inline_markdown(text: str) -> str:
    """Convert common inline markdown (bold, italic, code) to ReportLab XML tags safely."""
    # First escape XML special characters (&, <, >)
    safe = xml_escape(text)

    # Convert **bold** to <b>bold</b>
    safe = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", safe)

    # Convert *italic* or _italic_ to <i>italic</i>
    safe = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"<i>\1</i>", safe)
    safe = re.sub(r"(?<!_)_(?!_)(.+?)(?<!_)_(?!_)", r"<i>\1</i>", safe)

    # Convert `code` to Courier font
    safe = re.sub(r"`(.+?)`", r'<font face="Courier" color="#4f46e5">\1</font>', safe)

    return safe


def parse_markdown_table(lines: List[str]) -> Optional[Table]:
    """Parse markdown table rows (| col1 | col2 |) into a styled ReportLab Table."""
    raw_rows = []
    for line in lines:
        stripped = line.strip()
        if not stripped.startswith("|") or not stripped.endswith("|"):
            continue
        cells = [c.strip() for c in stripped.strip("|").split("|")]
        # Skip separator line like | :--- | :--- | or | --- | --- |
        if all(re.match(r"^:?-+:?$", c) for c in cells if c):
            continue
        raw_rows.append(cells)

    if not raw_rows:
        return None

    styles = getSampleStyleSheet()
    cell_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontSize=9,
        leading=11,
        textColor=colors.HexColor("#1e293b"),
    )
    header_style = ParagraphStyle(
        "TableHeader",
        parent=styles["Normal"],
        fontSize=9,
        leading=11,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#ffffff"),
    )

    flowable_rows = []
    for r_idx, row in enumerate(raw_rows):
        flowable_row = []
        for cell in row:
            st = header_style if r_idx == 0 else cell_style
            safe_text = format_inline_markdown(cell)
            flowable_row.append(Paragraph(safe_text, st))
        flowable_rows.append(flowable_row)

    table = Table(flowable_rows, hAlign="LEFT")
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4f46e5")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#f8fafc"), colors.HexColor("#ffffff")]),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
    ]))
    return table


class NumberedCanvas:
    """Canvas callback to add footer with page number and timestamp."""
    def __init__(self, canvas, doc):
        self.canvas = canvas
        self.doc = doc

    def draw_footer(self, page_num):
        self.canvas.saveState()
        self.canvas.setFont("Helvetica", 8)
        self.canvas.setFillColor(colors.HexColor("#64748b"))

        # Footer text
        footer_text = "Generated by AetherMind Document Intelligence Platform"
        page_str = f"Page {page_num}"

        self.canvas.drawString(54, 30, footer_text)
        self.canvas.drawRightString(612 - 54, 30, page_str)
        self.canvas.restoreState()


def generate_pdf_document(
    title: str,
    content: str,
    filename: Optional[str] = None,
    author: str = "AetherMind AI",
    subtitle: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Generate a professional, downloadable PDF from text content using ReportLab.
    Parses Markdown headings, paragraphs, bullet points, and tables.
    Returns metadata including file_path and download_url.
    """
    if not title or not title.strip():
        title = "AetherMind Document"
    if not content or not content.strip():
        content = "No content provided."

    clean_title = title.strip()
    pdf_id = f"pdf-{int(time.time() * 1000)}-{uuid.uuid4().hex[:6]}"

    if filename:
        actual_filename = sanitize_filename(filename)
    else:
        # Create descriptive filename from title
        slug = re.sub(r"[^a-zA-Z0-9_\-]", "_", clean_title.lower())[:32].strip("_")
        actual_filename = f"{slug or 'document'}_{uuid.uuid4().hex[:4]}.pdf"

    output_path = STORAGE_DIR / f"{pdf_id}_{actual_filename}"

    # Setup ReportLab Document
    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "AetherTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1e1b4b"),
        spaceAfter=4,
    )

    subtitle_style = ParagraphStyle(
        "AetherSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=12,
    )

    h1_style = ParagraphStyle(
        "AetherH1",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#4338ca"),
        spaceBefore=14,
        spaceAfter=6,
    )

    h2_style = ParagraphStyle(
        "AetherH2",
        parent=styles["Heading3"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=15,
        textColor=colors.HexColor("#334155"),
        spaceBefore=10,
        spaceAfter=4,
    )

    body_style = ParagraphStyle(
        "AetherBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#1e293b"),
        spaceAfter=6,
    )

    bullet_style = ParagraphStyle(
        "AetherBullet",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#334155"),
        leftIndent=15,
        firstLineIndent=-10,
        spaceAfter=4,
    )

    story = []

    # Document Header
    story.append(Paragraph(format_inline_markdown(clean_title), title_style))

    gen_time = datetime.now().strftime("%B %d, %Y at %I:%M %p")
    header_meta = f"Created by {author} • {gen_time}"
    if subtitle:
        header_meta = f"{subtitle} • {header_meta}"
    story.append(Paragraph(format_inline_markdown(header_meta), subtitle_style))

    # Divider bar
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#e0e7ff"), spaceAfter=14))

    # Process content line by line
    raw_lines = content.splitlines()
    i = 0
    while i < len(raw_lines):
        line = raw_lines[i]
        stripped = line.strip()

        # Check for Markdown table block
        if stripped.startswith("|") and stripped.endswith("|"):
            table_lines = []
            while i < len(raw_lines) and raw_lines[i].strip().startswith("|") and raw_lines[i].strip().endswith("|"):
                table_lines.append(raw_lines[i])
                i += 1
            tbl = parse_markdown_table(table_lines)
            if tbl:
                story.append(tbl)
                story.append(Spacer(1, 10))
            continue

        # Blank line
        if not stripped:
            story.append(Spacer(1, 6))
            i += 1
            continue

        # Markdown Headings
        if stripped.startswith("### "):
            heading_text = stripped[4:]
            story.append(Paragraph(format_inline_markdown(heading_text), h2_style))
        elif stripped.startswith("## "):
            heading_text = stripped[3:]
            story.append(Paragraph(format_inline_markdown(heading_text), h1_style))
        elif stripped.startswith("# "):
            heading_text = stripped[2:]
            story.append(Paragraph(format_inline_markdown(heading_text), title_style))
        # Bullet list item
        elif stripped.startswith(("- ", "* ", "• ")):
            item_text = stripped[2:]
            bullet_p = f"• {format_inline_markdown(item_text)}"
            story.append(Paragraph(bullet_p, bullet_style))
        # Numbered list item
        elif re.match(r"^\d+\.\s+", stripped):
            num_match = re.match(r"^(\d+\.)\s+(.+)$", stripped)
            if num_match:
                item_text = f"<b>{num_match.group(1)}</b> {format_inline_markdown(num_match.group(2))}"
                story.append(Paragraph(item_text, bullet_style))
            else:
                story.append(Paragraph(format_inline_markdown(stripped), body_style))
        else:
            # Standard paragraph
            story.append(Paragraph(format_inline_markdown(stripped), body_style))

        i += 1

    # Build document
    def on_page(canvas, document):
        NumberedCanvas(canvas, document).draw_footer(canvas.getPageNumber())

    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)

    file_size = output_path.stat().st_size

    result = {
        "pdf_id": pdf_id,
        "filename": actual_filename,
        "file_path": str(output_path),
        "file_size": file_size,
        "title": clean_title,
        "download_url": f"/api/pdf/download/{pdf_id}",
        "created_at": datetime.utcnow().isoformat(),
    }

    # Register in memory
    GENERATED_PDF_REGISTRY[pdf_id] = result

    return result


def get_generated_pdf(pdf_id: str) -> Optional[Dict[str, Any]]:
    """Retrieve metadata of a generated PDF by its ID."""
    # Check memory registry first
    if pdf_id in GENERATED_PDF_REGISTRY:
        info = GENERATED_PDF_REGISTRY[pdf_id]
        if os.path.exists(info["file_path"]):
            return info

    # Look in storage directory for matching filename prefix
    for path in STORAGE_DIR.glob(f"{pdf_id}_*"):
        if path.is_file():
            filename = path.name[len(pdf_id) + 1 :]
            info = {
                "pdf_id": pdf_id,
                "filename": filename,
                "file_path": str(path),
                "file_size": path.stat().st_size,
                "title": filename.replace(".pdf", "").replace("_", " ").title(),
                "download_url": f"/api/pdf/download/{pdf_id}",
                "created_at": datetime.fromtimestamp(path.stat().st_ctime).isoformat(),
            }
            GENERATED_PDF_REGISTRY[pdf_id] = info
            return info

    return None
